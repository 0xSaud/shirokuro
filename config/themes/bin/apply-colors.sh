#!/usr/bin/env bash
# Regenerate the Material 3 scheme and push it everywhere.
#
# Colours come from the current wallpaper by default, which is the point: the
# wallpaper changes often, so the palette should follow it instead of the user
# hunting for a named theme that happens to match.
#
#   apply-colors.sh                 # use whatever settings.json says
#   apply-colors.sh --source '#88c0d0'   # force a source colour (manual mode)
#   apply-colors.sh --wallpaper          # force wallpaper mode
set -euo pipefail

QS="$HOME/.config/quickshell"
CFG="$HOME/.config"
SETTINGS="$QS/settings.json"
COLORS="$QS/colors.json"
STATE="$HOME/.config/themes/state.json"
GEN="$HOME/.config/themes/bin/gen-colors.py"
CACHE="$HOME/.cache/wallpaper-frame.png"

mkdir -p "$QS" "$(dirname "$CACHE")"
[ -f "$SETTINGS" ] || cat > "$SETTINGS" <<'EOF'
{
  "colorMode": "wallpaper",
  "sourceColor": "#88c0d0",
  "scheme": "dark",
  "vivid": 1.0
}
EOF

get() { jq -r "$1 // empty" "$SETTINGS" 2>/dev/null || true; }

mode="$(get .colorMode)";   [ -n "$mode" ]   || mode="wallpaper"
source_col="$(get .sourceColor)"; [ -n "$source_col" ] || source_col="#88c0d0"
vivid="$(get .vivid)";      [ -n "$vivid" ]  || vivid="1.0"
harmony="$(get .harmony)"; [ -n "$harmony" ] || harmony="30"
scheme="$(get .scheme)";    [ -n "$scheme" ] || scheme="dark"
# 0 = Material pastel accents, 1 = deep earthy accents. See gen-colors.py --deep.
deep="$(get .deep)";        [ -n "$deep" ]   || deep="0"
# 0 = near-white light scheme, 1 = sand-paper light scheme. See gen-colors.py --paper.
paper="$(get .paper)";      [ -n "$paper" ]  || paper="0"
# 1 = ink scheme: grey surfaces, steel side accents, one coloured accent.
mono="$(get .mono)";        [ -n "$mono" ]   || mono="0"

while [ $# -gt 0 ]; do
    case "$1" in
        --source) mode="manual"; source_col="$2"; shift 2 ;;
        --wallpaper) mode="wallpaper"; shift ;;
        --vivid) vivid="$2"; shift 2 ;;
        --harmony) harmony="$2"; shift 2 ;;
        --deep) deep="$2"; shift 2 ;;
        --paper) paper="$2"; shift 2 ;;
        --mono) mono="$2"; shift 2 ;;
        *) shift ;;
    esac
done

# Persist whatever we were told to use, so the panels and the next run agree.
tmp="$(mktemp)"
jq --arg m "$mode" --arg s "$source_col" --argjson v "$vivid" --argjson h "$harmony" --argjson d "$deep" --argjson p "$paper" --argjson n "$mono" \
   '.colorMode=$m | .sourceColor=$s | .vivid=$v | .harmony=$h | .deep=$d | .paper=$p | .mono=$n' "$SETTINGS" > "$tmp" && mv "$tmp" "$SETTINGS"

# ---------------------------------------------------------------- pick a source
if [ "$mode" = "manual" ]; then
    "$GEN" --source "$source_col" --vivid "$vivid" --harmony "$harmony" --deep "$deep" --paper "$paper" --mono "$mono" --out "$COLORS"
else
    wp="$(jq -r '.wallpaper // empty' "$STATE" 2>/dev/null || true)"
    if [ -z "$wp" ] || [ ! -f "$wp" ]; then
        # No usable wallpaper recorded; fall back to the stored accent so the
        # shell still gets a complete scheme rather than no colours at all.
        "$GEN" --source "$source_col" --vivid "$vivid" --harmony "$harmony" --deep "$deep" --paper "$paper" --mono "$mono" --out "$COLORS"
    else
        img="$wp"
        case "${wp,,}" in
            *.mp4|*.mkv|*.webm|*.gif|*.mov|*.avi|*.m4v)
                # Video/animated wallpaper: sample one frame to derive colour from.
                ffmpeg -y -ss 00:00:01 -i "$wp" -frames:v 1 -vf "scale=320:-1" "$CACHE" >/dev/null 2>&1 \
                  || ffmpeg -y -i "$wp" -frames:v 1 -vf "scale=320:-1" "$CACHE" >/dev/null 2>&1 || true
                [ -f "$CACHE" ] && img="$CACHE"
                ;;
        esac
        "$GEN" --image "$img" --vivid "$vivid" --harmony "$harmony" --deep "$deep" --paper "$paper" --mono "$mono" --out "$COLORS"
    fi
fi

[ -f "$COLORS" ] || { echo "apply-colors: generation failed" >&2; exit 1; }

c() { jq -r ".${scheme}.$1" "$COLORS"; }
hexbare() { echo "${1#\#}"; }

primary="$(c primary)"
surface="$(c surface)"
onsurface="$(c onSurface)"
outline="$(c outline)"
surf_hi="$(c surfaceContainerHigh)"
prim_cont="$(c primaryContainer)"
on_prim="$(c onPrimary)"
err="$(c error)"

# ---------------------------------------------------------------- Hyprland borders
# Ink look: a pale hairline on the focused window, a dark one on the rest.
# The accent colour is deliberately NOT used here; it stays rare.
b_act="rgba($(hexbare "$onsurface")cc)"
b_ina="rgba($(hexbare "$(c surfaceContainerHighest)")ff)"
cat > "$CFG/hypr/theme.conf" <<EOF
# AUTO-GENERATED by apply-colors.sh — source: $(jq -r .source "$COLORS") ($mode, $scheme)
general {
    col.active_border = $b_act
    col.inactive_border = $b_ina
}
EOF
if command -v hyprctl >/dev/null 2>&1 && hyprctl version >/dev/null 2>&1; then
    hyprctl keyword general:col.active_border   "$b_act" >/dev/null 2>&1 || true
    hyprctl keyword general:col.inactive_border "$b_ina" >/dev/null 2>&1 || true
fi

# ---------------------------------------------------------------- rofi (leftovers)
cat > "$CFG/rofi/theme-colors.rasi" <<EOF
/* AUTO-GENERATED by apply-colors.sh */
* {
    bg-col:       $surface;
    bg-col-light: $surf_hi;
    border-col:   $primary;
    selected-col: $primary;
    fg-col:       $onsurface;
    fg-col2:      $outline;
}
EOF

# ---------------------------------------------------------------- kitty
ansi_key="ansiDark"; [ "$scheme" = "light" ] && ansi_key="ansiLight"
{
  echo "# AUTO-GENERATED by apply-colors.sh"
  echo "foreground            $onsurface"
  echo "background            $surface"
  echo "selection_foreground  $on_prim"
  echo "selection_background  $primary"
  echo "cursor                $primary"
  echo "cursor_text_color     $surface"
  echo "url_color             $(c tertiary)"
  echo "active_tab_background $primary"
  echo "active_tab_foreground $on_prim"
  echo "inactive_tab_background $surf_hi"
  echo "inactive_tab_foreground $outline"
  echo "active_border_color   $primary"
  echo "inactive_border_color $outline"
  # The full 16-colour ANSI ramp. Without this kitty falls back to its own
  # defaults and the terminal stops matching the theme.
  jq -r --arg k "$ansi_key" '.[$k] | to_entries[] | "\(.key)                \(.value)"' "$COLORS"
} > "$CFG/kitty/current-theme.conf"
pkill -USR1 -x kitty 2>/dev/null || true

# ---------------------------------------------------------------- hyprlock
# The lock screen shown after sleep (and by the power menu). Written here so
# it follows the palette like everything else. Layout: everything hangs off a
# vertical accent stroke on the left, with the seal in the bottom-right corner.
lk_fg="$(hexbare "$onsurface")"
lk_dim="$(hexbare "$outline")"
lk_line="$(hexbare "$(c outlineVariant)")"
lk_bg="$(hexbare "$(c surfaceContainerLowest)")"
lk_acc="$(hexbare "$primary")"
cat > "$CFG/hypr/hyprlock.conf" <<EOF
# AUTO-GENERATED by apply-colors.sh — edit the template there, not this file.
#
# The keyboard is switched to English before this starts (hypridle.conf), the
# current layout is printed under the password field, and SUPER+Space changes
# it while locked (bindl in hyprland.conf).
general {
    hide_cursor = true
    grace = 0
    disable_loading_bar = true
}

background {
    monitor =
    path = screenshot
    blur_passes = 4
    blur_size = 9
    contrast = 0.9
    brightness = 0.38
    vibrancy = 0.0
}

# Accent stroke the whole block hangs from.
shape {
    monitor =
    size = 4, 330
    color = rgba(${lk_acc}ff)
    rounding = 2
    position = 110, 10
    halign = left
    valign = center
}

label {
    monitor =
    text = cmd[update:60000] echo "\$(date +"%A")"
    color = rgba(${lk_dim}ff)
    font_size = 20
    font_family = Open Sans Semibold
    position = 142, 150
    halign = left
    valign = center
}

label {
    monitor =
    text = cmd[update:1000] echo "\$(date +"%I:%M")"
    color = rgba(${lk_fg}ff)
    font_size = 118
    font_family = Montserrat Bold
    position = 134, 52
    halign = left
    valign = center
}

label {
    monitor =
    text = cmd[update:60000] echo "\$(date +"%d %B %Y")"
    color = rgba(${lk_fg}ff)
    font_size = 18
    font_family = Open Sans
    position = 142, -44
    halign = left
    valign = center
}

input-field {
    monitor =
    size = 330, 48
    outline_thickness = 1
    dots_size = 0.26
    dots_spacing = 0.5
    dots_center = false
    rounding = 10
    outer_color = rgba(${lk_line}ff)
    inner_color = rgba(${lk_bg}ee)
    font_color  = rgba(${lk_fg}ff)
    fade_on_empty = false
    placeholder_text = <span foreground="##${lk_dim}">Password</span>
    check_color = rgba(${lk_fg}ff)
    fail_color  = rgba(${lk_acc}ff)
    fail_text = <span foreground="##${lk_fg}">Wrong password. Check the layout below.</span>
    capslock_color = rgba(${lk_acc}ff)
    position = 142, -104
    halign = left
    valign = center
}

# Which keyboard layout the password is being typed in.
label {
    monitor =
    text = \$LAYOUT
    color = rgba(${lk_fg}ff)
    font_size = 12
    font_family = Open Sans Semibold
    position = 144, -150
    halign = left
    valign = center
}

label {
    monitor =
    text = SUPER + Space changes the keyboard layout
    color = rgba(${lk_dim}ff)
    font_size = 10
    font_family = Open Sans
    position = 144, -172
    halign = left
    valign = center
}

# The seal, bottom-right.
image {
    monitor =
    path = $HOME/.config/quickshell/assets/seal.png
    size = 58
    rounding = 0
    border_size = 0
    position = -70, 64
    halign = right
    valign = bottom
}

label {
    monitor =
    text = \$USER
    color = rgba(${lk_dim}ff)
    font_size = 11
    font_family = Open Sans Semibold
    position = -70, 40
    halign = right
    valign = bottom
}
EOF

# ---------------------------------------------------------------- bar bridge
# The bar still reads theme.json; keep it in step so it follows the wallpaper too.
cat > "$QS/theme.json" <<EOF
{
  "bg":        "$surface",
  "bg_alt":    "$surf_hi",
  "fg":        "$onsurface",
  "accent":    "$primary",
  "accent_fg": "$on_prim",
  "urgent":    "$err"
}
EOF

# ---------------------------------------------------------------- shell (starship, fzf, zsh)
# The prompt and fzf used to carry a hardcoded palette, so they stayed one
# colour while everything else followed the theme.
ansi() { jq -r --arg k "$ansi_key" --arg c "$1" '.[$k][$c]' "$COLORS"; }
onvar="$(c onSurfaceVariant)"
surf_top="$(c surfaceContainerHighest)"
outvar="$(c outlineVariant)"
tert="$(c tertiary)"

STAR="$CFG/starship.toml"
if [ -f "$STAR" ] && grep -q '^# >>> rice palette' "$STAR"; then
    blk="$(mktemp)"; tmp="$(mktemp)"
    cat > "$blk" <<EOF
[palettes.rice]
accent    = "$primary"
accent_fg = "$on_prim"
gold      = "$tert"
rose      = "$(c secondary)"
red       = "$err"
green     = "$(ansi color2)"
blue      = "$(ansi color4)"
cyan      = "$(ansi color6)"
fg        = "$onsurface"
dim       = "$onvar"
faint     = "$outline"
line      = "$outvar"
bg        = "$surface"
bg2       = "$surf_hi"
bg3       = "$surf_top"
EOF
    awk -v blk="$blk" '
        /^# >>> rice palette/ { print; while ((getline l < blk) > 0) print l; skip=1; next }
        /^# <<< rice palette/ { skip=0 }
        !skip { print }
    ' "$STAR" > "$tmp" && [ -s "$tmp" ] && cat "$tmp" > "$STAR"
    rm -f "$blk" "$tmp"
fi

cat > "$HOME/.config/themes/shell-theme.zsh" <<EOF
# AUTO-GENERATED by apply-colors.sh — sourced from ~/.zshrc
ZSH_AUTOSUGGEST_HIGHLIGHT_STYLE='fg=$outline'
export FZF_DEFAULT_OPTS="\${FZF_BASE_OPTS:-} \\
  --color=bg+:$surf_hi,bg:-1,gutter:-1,spinner:$tert,hl:$tert \\
  --color=fg:$onvar,fg+:$onsurface,header:$outline,info:$outline \\
  --color=pointer:$primary,marker:$tert,prompt:$primary,hl+:$tert \\
  --color=border:$outvar,separator:$outvar"
EOF

echo "colours: $(jq -r .source "$COLORS")  hue $(jq -r .hue "$COLORS")  harmony ${harmony}deg  mode $mode"
