#!/usr/bin/env bash
# Apply a theme everywhere: Quickshell bar, Hyprland borders, rofi.
# Usage: apply-theme.sh <theme-name>
set -euo pipefail

CFG="$HOME/.config"
THEMES="$CFG/themes/themes"
STATE="$CFG/themes/state.json"
name="${1:-}"

[ -z "$name" ] && { echo "usage: apply-theme.sh <name>"; exit 1; }
TF="$THEMES/$name.json"
[ -f "$TF" ] || { echo "theme not found: $TF"; exit 1; }

read -r bg bg_alt fg accent accent_fg urgent ba bi < <(jq -r \
  '[.bg,.bg_alt,.fg,.accent,.accent_fg,.urgent,.border_active,.border_inactive] | @tsv' "$TF")

# 1) Quickshell — it hot-reloads this file via FileView
cp "$TF" "$CFG/quickshell/theme.json"

# 2) rofi — generate the shared color palette every theme imports
cat > "$CFG/rofi/theme-colors.rasi" <<EOF
/* AUTO-GENERATED by apply-theme.sh — theme: $name */
* {
    bg-col:       $bg;
    bg-col-light: $bg_alt;
    border-col:   $accent;
    selected-col: $accent;
    fg-col:       $fg;
    fg-col2:      $accent_fg;
    bg:           $bg;
    bg-alt:       $bg_alt;
    fg:           $fg;
    accent:       $accent;
    accent-fg:    $accent_fg;
    urgent:       $urgent;
}
EOF

# 3) Hyprland — persistent sourced file + live update if running
cat > "$CFG/hypr/theme.conf" <<EOF
# AUTO-GENERATED by apply-theme.sh — theme: $name
general {
    col.active_border = rgba($ba)
    col.inactive_border = rgba($bi)
}
EOF
if command -v hyprctl >/dev/null 2>&1 && hyprctl version >/dev/null 2>&1; then
    hyprctl keyword general:col.active_border "rgba($ba)" >/dev/null 2>&1 || true
    hyprctl keyword general:col.inactive_border "rgba($bi)" >/dev/null 2>&1 || true
fi

# 3b) dunst notifications — themed, no icons, rounded
mkdir -p "$CFG/dunst"
cat > "$CFG/dunst/dunstrc" <<EOF
# AUTO-GENERATED by apply-theme.sh — theme: $name
[global]
    monitor = 0
    follow = mouse
    width = 380
    height = 300
    origin = top-right
    offset = 14x46
    notification_limit = 6
    progress_bar = true
    progress_bar_height = 8
    progress_bar_frame_width = 0
    indicate_hidden = yes
    transparency = 0
    separator_height = 2
    padding = 14
    horizontal_padding = 18
    text_icon_padding = 0
    frame_width = 2
    gap_size = 6
    sort = yes
    font = FiraCode Nerd Font Propo 11
    line_height = 3
    markup = full
    format = "<b>%s</b>\\n%b"
    alignment = left
    vertical_alignment = center
    ellipsize = end
    stack_duplicates = true
    hide_duplicate_count = false
    show_indicators = no
    icon_position = off
    min_icon_size = 0
    max_icon_size = 0
    enable_recursive_icon_lookup = false
    corner_radius = 14
    mouse_left_click = close_current
    mouse_middle_click = do_action, close_current
    mouse_right_click = close_all

[urgency_low]
    background = "$bg"
    foreground = "$fg"
    frame_color = "$bg_alt"
    timeout = 3

[urgency_normal]
    background = "$bg"
    foreground = "$fg"
    frame_color = "$accent"
    timeout = 4

[urgency_critical]
    background = "$bg"
    foreground = "$fg"
    frame_color = "$urgent"
    timeout = 10
EOF
: # dunst disabled — Quickshell owns notifications now (dunstrc kept as backup)

# 3c) kitty — use a custom per-theme palette if one exists, else derive one
if [ -d "$CFG/kitty" ]; then
KCONF="$CFG/kitty/current-theme.conf"
KCUSTOM="$HOME/.config/themes/kitty/$name.conf"
if [ -f "$KCUSTOM" ]; then
    # hand-picked palette for this theme (drop a <name>.conf to customize any theme)
    { echo "# AUTO-GENERATED by apply-theme.sh — custom palette: $name"; cat "$KCUSTOM"; } > "$KCONF"
else
    cat > "$KCONF" <<EOF
# AUTO-GENERATED by apply-theme.sh — derived palette: $name
foreground            $fg
background            $bg
selection_foreground  $accent_fg
selection_background  $accent
cursor                $accent
cursor_text_color     $bg
url_color             $accent
url_style             single

color0  $bg
color8  $bg_alt
color1  $urgent
color9  $urgent
color2  #98c379
color10 #98c379
color3  #e5c07b
color11 #e5c07b
color4  $accent
color12 $accent
color5  #c678dd
color13 #c678dd
color6  $accent
color14 $accent
color7  $fg
color15 $fg

active_tab_foreground   $accent_fg
active_tab_background   $accent
inactive_tab_foreground $fg
inactive_tab_background $bg_alt
EOF
fi
# live-reload every running kitty (re-reads kitty.conf + the include on SIGUSR1)
pkill -SIGUSR1 -x kitty 2>/dev/null || true
fi

# 3e) hyprlock — themed lock screen
strip='#'; bgh="${bg#$strip}"; fgh="${fg#$strip}"; acch="${accent#$strip}"; urgh="${urgent#$strip}"
cat > "$CFG/hypr/hyprlock.conf" <<EOF
# AUTO-GENERATED by apply-theme.sh — theme: $name
general {
    hide_cursor = true
    grace = 0
    disable_loading_bar = true
}
background {
    monitor =
    path = screenshot
    blur_passes = 3
    blur_size = 8
    contrast = 0.9
    brightness = 0.7
}
input-field {
    monitor =
    size = 300, 56
    outline_thickness = 2
    dots_size = 0.28
    dots_spacing = 0.5
    dots_center = true
    rounding = 14
    outer_color = rgba(${acch}ff)
    inner_color = rgba(${bgh}ee)
    font_color  = rgba(${fgh}ff)
    fade_on_empty = false
    placeholder_text = <span foreground="##${fgh}"><i>Password…</i></span>
    check_color = rgba(${acch}ff)
    fail_color  = rgba(${urgh}ff)
    capslock_color = rgba(${urgh}ff)
    position = 0, -80
    halign = center
    valign = center
}
label {
    monitor =
    text = cmd[update:1000] echo "\$(date +"%I:%M %p")"
    color = rgba(${fgh}ff)
    font_size = 96
    font_family = FiraCode Nerd Font Propo
    position = 0, 220
    halign = center
    valign = center
}
label {
    monitor =
    text = Hi, reouii
    color = rgba(${acch}ff)
    font_size = 22
    font_family = FiraCode Nerd Font Propo
    position = 0, 130
    halign = center
    valign = center
}
EOF

# 3d) fastfetch — recolor keys/separator from the theme (jq keeps logo+icons+modules)
FF="$CFG/fastfetch/config.jsonc"
if [ -f "$FF" ] && command -v jq >/dev/null 2>&1; then
    hex2ansi() { local h="${1#\#}"; printf '38;2;%d;%d;%d' "0x${h:0:2}" "0x${h:2:2}" "0x${h:4:2}"; }
    A_ANSI="$(hex2ansi "$accent")"
    F_ANSI="$(hex2ansi "$fg")"
    [ -f "$FF.pre-claude.bak" ] || cp "$FF" "$FF.pre-claude.bak"
    tmp="$(mktemp)"
    if jq --arg acc "$A_ANSI" --arg fg2 "$F_ANSI" '
        (.display.color.separator) = $fg2
        | .modules |= [ to_entries[]
            | if (.value|type)=="object" and (.value|has("keyColor"))
              then .value + { keyColor: (if (.key % 2)==0 then $acc else $fg2 end) }
              else .value end ]
       ' "$FF" > "$tmp" 2>/dev/null && [ -s "$tmp" ]; then
        mv "$tmp" "$FF"
    else
        rm -f "$tmp"
    fi
fi

# 4) Persist choice
tmp="$(mktemp)"
[ -f "$STATE" ] || echo '{}' > "$STATE"
jq --arg t "$name" '.theme = $t' "$STATE" > "$tmp" && mv "$tmp" "$STATE"

echo "applied: $name"
